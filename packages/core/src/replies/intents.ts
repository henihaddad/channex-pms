/** The sections a question seems to be about, best match first; empty when nothing matched. */
export function detectIntents(question: string): readonly GuideSectionKind[] {
  const text = ` ${normaliseQuestion(question)} `;
  if (text.trim() === "") return [];
  const scored: Array<{ kind: GuideSectionKind; score: number; longest: number }> = [];
  for (const [kind, words] of Object.entries(KEYWORDS) as Array<
    [GuideSectionKind, readonly string[]]
  >) {
    let score = 0;
    let longest = 0;
    for (const w of words) {
      if (text.includes(` ${w} `) || text.includes(` ${w}`) || text.includes(`${w} `)) {
        score++;
        longest = Math.max(longest, w.length);
      }
    }
    if (score > 0) scored.push({ kind, score, longest });
  }
  // more distinct hits first, then the more specific phrase ("check out" over "out")
  return scored.sort((a, b) => b.score - a.score || b.longest - a.longest).map((s) => s.kind);
}
