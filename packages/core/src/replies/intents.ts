/**
 * Which guide section answers a guest's question, decided by the words they used.
 *
 * Keywords, not a model, and in the launch locales (spec 16 Q10) because a Tunisian
 * manager's guests write in French and Arabic. A keyword list is wrong sometimes; that
 * is why the draft is labelled with what it thinks was asked and a human presses send.
 */

/** Diacritics folded and Arabic normalised, so "Wi-Fi", "wifi" and "واي-فاي" all land. */
export function normaliseQuestion(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "") // Latin accents
    .replace(/[ً-ْـ]/g, "") // Arabic harakat and tatweel
    .replace(/[أإآ]/g, "ا") // alef forms
    .replace(/ى/g, "ي") // alef maqsura
    .replace(/ة/g, "ه") // ta marbuta
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

